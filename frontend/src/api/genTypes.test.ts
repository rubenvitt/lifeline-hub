import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { GenTypesError, generateTypes } from '../../scripts/gen-types.mjs';

/** Baut ein Dokument mit genau diesen Schemas. */
function doc(schemas: Record<string, unknown>) {
  return { openapi: '3.1.0', paths: {}, components: { schemas } };
}

/** Der Block eines einzelnen Schemas, wie ihn die Datei zwischen `schemas: {` und `};` trägt. */
function schemaBlock(schemas: Record<string, unknown>): string {
  const out = generateTypes(doc(schemas));
  const start = out.indexOf('    schemas: {\n') + '    schemas: {\n'.length;
  const end = out.indexOf('\n    };\n    responses: never;');
  return out.slice(start, end);
}

describe('generateTypes (LLH-2141)', () => {
  it('erzeugt die committete types.generated.ts aus openapi.json', () => {
    const input = JSON.parse(readFileSync('src/api/openapi.json', 'utf8'));
    const expected = readFileSync('src/api/types.generated.ts', 'utf8');
    expect(generateTypes(input)).toBe(expected);
  });

  it('trägt den eigenen Dateikopf und die leeren Exporte', () => {
    const out = generateTypes(doc({ A: { type: 'string' } }));
    expect(
      out.startsWith('/**\n * This file was auto-generated by frontend/scripts/gen-types.mjs.\n'),
    ).toBe(true);
    expect(out).toContain('export type paths = Record<string, never>;\n');
    expect(out.endsWith('export type operations = Record<string, never>;\n')).toBe(true);
  });

  it('macht Felder ohne required optional und nullbare Typen zur Vereinigung mit null', () => {
    expect(
      schemaBlock({
        A: {
          type: 'object',
          required: ['id'],
          properties: {
            id: { type: 'integer', format: 'int64' },
            name: { type: ['string', 'null'] },
          },
        },
      }),
    ).toBe(
      [
        '        A: {',
        '            /** Format: int64 */',
        '            id: number;',
        '            name?: string | null;',
        '        };',
      ].join('\n'),
    );
  });

  it('schreibt Aufzählungen, Verweise, Listen und Maps wie openapi-typescript', () => {
    expect(
      schemaBlock({
        E: { type: 'string', description: 'Status.', enum: ['a', 'b'] },
        M: {
          type: 'object',
          required: ['e', 'l', 'm'],
          properties: {
            e: { $ref: '#/components/schemas/E' },
            l: { type: 'array', items: { $ref: '#/components/schemas/E' } },
            m: {
              type: 'object',
              additionalProperties: { type: 'string' },
              propertyNames: { type: 'string' },
            },
          },
        },
        Leer: { type: 'object' },
      }),
    ).toBe(
      [
        '        /**',
        '         * @description Status.',
        '         * @enum {string}',
        '         */',
        '        E: "a" | "b";',
        '        M: {',
        '            e: components["schemas"]["E"];',
        '            l: components["schemas"]["E"][];',
        '            m: {',
        '                [key: string]: string;',
        '            };',
        '        };',
        '        Leer: Record<string, never>;',
      ].join('\n'),
    );
  });

  it('setzt allOf als Schnittmenge, oneOf als Vereinigung und mehrzeilige Beschreibungen eingerückt', () => {
    expect(
      schemaBlock({
        D: {
          allOf: [
            { $ref: '#/components/schemas/B' },
            { type: 'object', required: ['x'], properties: { x: { type: 'boolean' } } },
          ],
          description: 'Zeile eins\nZeile zwei mit */ darin.',
        },
        O: { oneOf: [{ type: 'null' }, { $ref: '#/components/schemas/B' }] },
        L: {
          type: 'array',
          items: {
            oneOf: [
              { type: 'object', required: ['k'], properties: { k: { type: 'number' } } },
              { type: 'string' },
            ],
          },
        },
      }),
    ).toBe(
      [
        '        /**',
        '         * @description Zeile eins',
        '         *     Zeile zwei mit *\\/ darin.',
        '         */',
        '        D: components["schemas"]["B"] & {',
        '            x: boolean;',
        '        };',
        '        O: null | components["schemas"]["B"];',
        '        L: ({',
        '            k: number;',
        '        } | string)[];',
      ].join('\n'),
    );
  });

  it('bricht bei einem unbekannten Schlüssel mit Schema und Pfad ab', () => {
    expect(() => generateTypes(doc({ X: { anyOf: [{ type: 'string' }] } }))).toThrow(GenTypesError);
    expect(() => generateTypes(doc({ X: { anyOf: [{ type: 'string' }] } }))).toThrow(
      /#\/components\/schemas\/X.*anyOf/,
    );
  });

  it('bricht bei einer unbekannten type-Angabe ab', () => {
    expect(() =>
      generateTypes(doc({ Y: { type: 'object', properties: { f: { type: 'datei' } } } })),
    ).toThrow(/#\/components\/schemas\/Y\/properties\/f.*datei/);
  });

  it('bricht ab, wenn das Dokument Routen trägt', () => {
    expect(() => generateTypes({ ...doc({}), paths: { '/x': {} } })).toThrow(GenTypesError);
  });
});
