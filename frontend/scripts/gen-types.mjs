/**
 * Typ-Codegen (LLH-2141, ADR-0106): schreibt `src/api/types.generated.ts` aus `src/api/openapi.json`.
 *
 * Löst openapi-typescript 7.13 ab, das die Compiler-API von TypeScript 6 brauchte. Die Ausgabe
 * ahmt dessen Form nach (Regeln aus `transform/schema-object` und `lib/ts` von 7.13, Optionen wie
 * im früheren Aufruf: keine). Maßstab ist die committete Datei; `src/api/genTypes.test.ts` prüft
 * sie Byte für Byte.
 *
 * Abgedeckt sind nur die Konstrukte, die utoipa heute erzeugt. Jeder andere Schlüssel und jede
 * andere `type`-Angabe bricht mit Schema und Pfad ab (`GenTypesError`), statt still `unknown`
 * zu erzeugen. Kommt eine neue Form hinzu, wird sie hier nach dem Vorbild von 7.13 ergänzt.
 *
 * Aufruf: `node scripts/gen-types.mjs <openapi.json> -o <types.generated.ts>` (Skript `gen:types`).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { argv, exit } from 'node:process';
import { pathToFileURL } from 'node:url';

export class GenTypesError extends Error {
  /** @param {string} path @param {string} message */
  constructor(path, message) {
    super(`${path}: ${message}`);
    this.name = 'GenTypesError';
    this.path = path;
  }
}

const HEADER = `/**
 * This file was auto-generated by frontend/scripts/gen-types.mjs.
 * Do not make direct changes to the file.
 */

`;

const SCHEMA_REF_PREFIX = '#/components/schemas/';
const ALLOWED_KEYS = new Set([
  'type',
  'properties',
  'required',
  'items',
  'enum',
  'oneOf',
  'allOf',
  '$ref',
  'additionalProperties',
  'propertyNames',
  'format',
  'minimum',
  'description',
]);
const ALLOWED_TYPES = new Set([
  'string',
  'integer',
  'number',
  'boolean',
  'array',
  'object',
  'null',
]);
const PRIMITIVE_KEYWORDS = new Set(['boolean', 'never', 'null', 'number', 'string', 'undefined']);
const JS_PROPERTY_INDEX_RE = /^[A-Za-z_$][A-Za-z_$0-9]*$/;
const LB_RE = /\r?\n/g;
const COMMENT_RE = /\*\//g;
const INDENT = '    ';

// --- Typknoten -------------------------------------------------------------------------------

const kw = (name) => ({ k: 'kw', name });
const NEVER = kw('never');
const UNKNOWN = kw('unknown');
const NULL = kw('null');
const RECORD_NEVER = { k: 'raw', text: 'Record<string, never>' };

const isPrimitive = (t) => t.k === 'kw' && PRIMITIVE_KEYWORDS.has(t.name);

/** Wie `tsDedupe`: doppelte Grundtypen (string, null, …) fallen weg, alles andere bleibt. */
function dedupe(types) {
  const seen = new Set();
  return types.filter((t) => {
    if (t.k !== 'kw') return true;
    if (seen.has(t.name)) return false;
    if (isPrimitive(t)) seen.add(t.name);
    return true;
  });
}

function union(types) {
  if (types.length === 0) return NEVER;
  if (types.length === 1) return types[0];
  return { k: 'union', types: dedupe(types) };
}

function intersection(types) {
  if (types.length === 0) return NEVER;
  if (types.length === 1) return types[0];
  return { k: 'inter', types: dedupe(types) };
}

const array = (el) => ({ k: 'arr', el });
const object = (members) => ({ k: 'obj', members });

function ref(path, $ref) {
  if (typeof $ref !== 'string' || !$ref.startsWith(SCHEMA_REF_PREFIX)) {
    throw new GenTypesError(path, `nicht unterstützter $ref ${JSON.stringify($ref)}`);
  }
  const name = $ref.slice(SCHEMA_REF_PREFIX.length);
  return { k: 'raw', text: `components["schemas"][${JSON.stringify(name)}]` };
}

function literal(path, value) {
  if (typeof value === 'string') return { k: 'raw', text: JSON.stringify(value) };
  if (typeof value === 'number')
    return { k: 'raw', text: value < 0 ? `-${Math.abs(value)}` : String(value) };
  if (typeof value === 'boolean') return { k: 'raw', text: String(value) };
  if (value === null) return NULL;
  throw new GenTypesError(path, `nicht unterstützter enum-Wert ${JSON.stringify(value)}`);
}

// --- Kommentare (wie `addJSDocComment`) -----------------------------------------------------

function commentFor(schema) {
  const output = [];
  if (schema.format) output.push(`Format: ${schema.format}`);
  if (schema.description !== undefined && schema.description !== '') {
    output.push(`@description ${String(schema.description).trim().replace(LB_RE, '\n *     ')}`);
  }
  if (schema.enum) {
    let type = 'unknown';
    if (Array.isArray(schema.type)) type = schema.type.join('|');
    else if (typeof schema.type === 'string') type = schema.type;
    output.push(`@enum {${type}}`);
  }
  if (output.length === 0) return undefined;
  const multiLine = output.some((item) => item.includes('\n'));
  const text =
    output.length === 1 && !multiLine
      ? `* ${output.join('\n')} `
      : `*\n * ${output.join('\n * ')}\n `;
  return `/*${text.replace(COMMENT_RE, '*\\/')}*/`;
}

// --- Prüfung der Eingabe ---------------------------------------------------------------------

function validate(path, schema) {
  if (schema === null || typeof schema !== 'object' || Array.isArray(schema)) {
    throw new GenTypesError(
      path,
      `Schema erwartet, gefunden ${Array.isArray(schema) ? 'Array' : typeof schema}`,
    );
  }
  for (const [key, value] of Object.entries(schema)) {
    if (value !== undefined && !ALLOWED_KEYS.has(key)) {
      throw new GenTypesError(path, `unbekannter Schlüssel "${key}"`);
    }
  }
  if ('type' in schema && schema.type !== undefined) {
    const types = Array.isArray(schema.type) ? schema.type : [schema.type];
    for (const t of types) {
      if (!ALLOWED_TYPES.has(t))
        throw new GenTypesError(path, `unbekannte type-Angabe ${JSON.stringify(t)}`);
    }
  }
}

// --- Umsetzung (wie `transformSchemaObject`) -------------------------------------------------

function createGenerator(schemas) {
  function transform(schema, path) {
    if (schema === true) return UNKNOWN;
    if (!schema) return NEVER;
    validate(path, schema);
    if ('$ref' in schema) return ref(path, schema.$ref);

    if (
      Array.isArray(schema.enum) &&
      (!('type' in schema) || schema.type !== 'object') &&
      !('properties' in schema) &&
      !('additionalProperties' in schema)
    ) {
      const members = schema.enum.map((v, i) => literal(`${path}/enum/${i}`, v));
      if (Array.isArray(schema.type) && schema.type.includes('null')) members.push(NULL);
      return union(members);
    }

    let finalType;
    const core = transformCore(schema, path);
    const allOf = (schema.allOf ?? []).map((item, i) =>
      transformAllOfItem(item, schema.required, `${path}/allOf/${i}`),
    );
    if (core || allOf.length) {
      const allOfType = allOf.length ? intersection(allOf) : undefined;
      finalType = intersection([...(core ? [core] : []), ...(allOfType ? [allOfType] : [])]);
    }

    const oneOfItems =
      schema.oneOf || ('type' in schema && schema.type === 'object' && schema.enum) || [];
    const oneOf = oneOfItems.map((item, i) => transform(item, `${path}/oneOf/${i}`));
    if (oneOf.length) {
      finalType = oneOf.every(isPrimitive)
        ? union([...(finalType ? [finalType] : []), ...oneOf])
        : intersection([...(finalType ? [finalType] : []), union(oneOf)]);
    }

    if (!finalType) finalType = 'type' in schema ? RECORD_NEVER : UNKNOWN;
    return finalType;
  }

  function transformAllOfItem(item, required, path) {
    if (item && typeof item === 'object' && '$ref' in item) {
      const type = transform(item, path);
      const target = schemas[String(item.$ref).slice(SCHEMA_REF_PREFIX.length)];
      if (target && typeof target === 'object' && 'properties' in target) {
        const lifted = (required ?? []).filter((key) => !!target.properties?.[key]);
        if (lifted.length) {
          throw new GenTypesError(
            path,
            'allOf mit $ref und required auf dessen Felder wird nicht unterstützt',
          );
        }
      }
      return type;
    }
    const itemRequired = [...(required ?? [])];
    if (item && typeof item === 'object' && Array.isArray(item.required))
      itemRequired.push(...item.required);
    return transform({ ...item, required: itemRequired }, path);
  }

  function transformCore(schema, path) {
    if ('type' in schema && schema.type) {
      const { type } = schema;
      if (type === 'null') return NULL;
      if (type === 'string') return kw('string');
      if (type === 'number' || type === 'integer') return kw('number');
      if (type === 'boolean') return kw('boolean');
      if (type === 'array') {
        if (Array.isArray(schema.items))
          throw new GenTypesError(path, 'Tupel (items als Liste) wird nicht unterstützt');
        let itemType = UNKNOWN;
        if (schema.items) {
          const inner = transform(schema.items, `${path}/items`);
          itemType =
            typeof schema.items === 'object' &&
            schema.items !== null &&
            schema.items.type === 'array'
              ? array(inner)
              : inner;
        }
        return itemType.k === 'arr' ? itemType : array(itemType);
      }
      if (Array.isArray(type)) {
        const types = [];
        if (Array.isArray(schema.oneOf)) {
          for (const t of type) {
            if (
              ['boolean', 'string', 'number', 'integer', 'null'].includes(t) &&
              schema.oneOf.find(
                (o) => typeof o === 'object' && o !== null && 'type' in o && o.type === t,
              )
            ) {
              continue;
            }
            types.push(
              t === 'null' ? NULL : transform({ ...schema, type: t, oneOf: undefined }, path),
            );
          }
        } else {
          for (const t of type)
            types.push(t === 'null' ? NULL : transform({ ...schema, type: t }, path));
        }
        return union(types);
      }
    }

    const members = [];
    const properties = schema.properties ?? {};
    if (
      Object.keys(properties).length ||
      ('additionalProperties' in schema && schema.additionalProperties)
    ) {
      for (const [key, value] of Object.entries(properties)) {
        const propPath = `${path}/properties/${key}`;
        if ((typeof value !== 'object' && typeof value !== 'boolean') || Array.isArray(value)) {
          throw new GenTypesError(propPath, 'Schema oder boolean erwartet');
        }
        const optional = !schema.required?.includes(key);
        const type =
          typeof value === 'object' && '$ref' in value
            ? (validate(propPath, value), ref(propPath, value.$ref))
            : transform(value, propPath);
        members.push({
          comment: typeof value === 'object' ? commentFor(value) : undefined,
          name: propertyName(key),
          optional,
          type,
        });
      }

      const ap = schema.additionalProperties;
      const indexTypes = [];
      if (typeof ap === 'object' && ap !== null && Object.keys(ap).length) {
        indexTypes.push(transform(ap, `${path}/additionalProperties`));
      }
      if (ap === true || (typeof ap === 'object' && ap !== null && Object.keys(ap).length === 0)) {
        indexTypes.push(UNKNOWN);
      }
      if (indexTypes.length === 0) return members.length ? object(members) : undefined;
      return intersection([
        ...(members.length ? [object(members)] : []),
        object([{ index: union(indexTypes) }]),
      ]);
    }
    return members.length ? object(members) : undefined;
  }

  return transform;
}

function propertyName(key) {
  if (String(Number(key)) === key && key[0] !== '-') return key;
  return JS_PROPERTY_INDEX_RE.test(key) ? key : JSON.stringify(key);
}

// --- Ausgabe (wie der Printer von TypeScript) ------------------------------------------------

function print(type, indent) {
  switch (type.k) {
    case 'kw':
      return type.name;
    case 'raw':
      return type.text;
    case 'union':
      return type.types.map((t) => print(t, indent)).join(' | ');
    case 'inter':
      return type.types
        .map((t) => (t.k === 'union' ? `(${print(t, indent)})` : print(t, indent)))
        .join(' & ');
    case 'arr': {
      const el = print(type.el, indent);
      return type.el.k === 'union' || type.el.k === 'inter' ? `(${el})[]` : `${el}[]`;
    }
    case 'obj':
      return `{\n${printMembers(type.members, indent + INDENT)}${indent}}`;
    default:
      throw new Error(`unbekannter Typknoten ${type.k}`);
  }
}

function printMembers(members, indent) {
  let out = '';
  for (const member of members) {
    if (member.comment) {
      out += member.comment
        .split('\n')
        // Der Printer von TypeScript schreibt Kommentarzeilen ohne Leerzeichen am Ende.
        .map((line) => (indent + line).trimEnd())
        .join('\n');
      out += '\n';
    }
    if ('index' in member) {
      out += `${indent}[key: string]: ${print(member.index, indent)};\n`;
    } else {
      out += `${indent}${member.name}${member.optional ? '?' : ''}: ${print(member.type, indent)};\n`;
    }
  }
  return out;
}

// --- Datei -----------------------------------------------------------------------------------

/**
 * Erzeugt den ganzen Inhalt von `types.generated.ts` aus einem OpenAPI-Dokument.
 * @param {unknown} doc
 * @returns {string}
 */
export function generateTypes(doc) {
  if (doc === null || typeof doc !== 'object')
    throw new GenTypesError('#', 'OpenAPI-Dokument erwartet');
  const { paths, webhooks, components } = /** @type {Record<string, any>} */ (doc);
  if (paths && Object.keys(paths).length) {
    throw new GenTypesError(
      '#/paths',
      'Routen werden nicht unterstützt (openapi.json trägt nur Schemas)',
    );
  }
  if (webhooks && Object.keys(webhooks).length) {
    throw new GenTypesError('#/webhooks', 'Webhooks werden nicht unterstützt');
  }
  for (const key of Object.keys(components ?? {})) {
    if (key !== 'schemas')
      throw new GenTypesError(`#/components/${key}`, `unbekannter Schlüssel "${key}"`);
  }
  const schemas = components?.schemas ?? {};
  const transform = createGenerator(schemas);
  const members = Object.entries(schemas).map(([name, schema]) => {
    const path = `${SCHEMA_REF_PREFIX}${name}`;
    const type = transform(schema, path);
    return { comment: commentFor(schema), name: propertyName(name), optional: false, type };
  });

  const schemasType = members.length ? object(members) : NEVER;
  const componentMembers = [
    { name: 'schemas', optional: false, type: schemasType },
    ...['responses', 'parameters', 'requestBodies', 'headers', 'pathItems'].map((name) => ({
      name,
      optional: false,
      type: NEVER,
    })),
  ];

  return (
    HEADER +
    'export type paths = Record<string, never>;\n' +
    'export type webhooks = Record<string, never>;\n' +
    `export interface components {\n${printMembers(componentMembers, INDENT)}}\n` +
    'export type $defs = Record<string, never>;\n' +
    'export type operations = Record<string, never>;\n'
  );
}

function main(args) {
  const outIndex = args.indexOf('-o');
  const input = args.find((a, i) => a !== '-o' && i !== outIndex + 1);
  const output = outIndex >= 0 ? args[outIndex + 1] : undefined;
  if (!input || !output) {
    console.error('Aufruf: node scripts/gen-types.mjs <openapi.json> -o <types.generated.ts>');
    return 2;
  }
  try {
    writeFileSync(output, generateTypes(JSON.parse(readFileSync(input, 'utf8'))));
  } catch (error) {
    console.error(error instanceof GenTypesError ? `gen-types: ${error.message}` : error);
    return 1;
  }
  console.log(`gen-types: ${output} geschrieben`);
  return 0;
}

if (argv[1] && import.meta.url === pathToFileURL(argv[1]).href) {
  exit(main(argv.slice(2)));
}
